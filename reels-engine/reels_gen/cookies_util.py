"""
Автоподхват Instagram-cookies из браузера (Chrome/Edge/...) и сохранение в файл.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / "assets"
COOKIES_FILE = ASSETS / "cookies_instagram.txt"
CONFIG_FILE = ASSETS / "ig_config.json"

BROWSER_ORDER = ("opera", "chrome", "edge", "brave", "firefox", "vivaldi")
ProgressCb = Callable[[str], None]


def _log(on_log: ProgressCb | None, msg: str) -> None:
    if on_log:
        on_log(msg)


def load_ig_config() -> dict:
    if CONFIG_FILE.exists():
        try:
            return json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            return {}
    return {}


def save_ig_config(data: dict) -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def cookies_has_sessionid(path: Path | None = None) -> bool:
    """В Netscape-файле есть непустой instagram sessionid — ключ авторизации.

    Без sessionid Playwright/веб-API не видят аккаунт (редирект на логин, HTTP 429).
    Такой файл считаем негодным, чтобы принудительно обновить cookies из браузера.
    """
    p = path or COOKIES_FILE
    if not p.exists():
        return False
    try:
        text = p.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False
    for ln in text.splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        parts = ln.split("\t")
        if len(parts) < 7:
            continue
        domain = parts[0].lower()
        name = parts[-2].strip().lower()
        value = parts[-1].strip()
        if name == "sessionid" and value and "instagram" in domain:
            return True
    return False


def cookies_file_ok(path: Path | None = None) -> bool:
    """Годен, только если в файле есть живой instagram sessionid."""
    return cookies_has_sessionid(path)


def _write_netscape(cookies: list[dict], path: Path) -> Path:
    """cookies: dicts with domain, name, value, path, secure, expires."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Netscape HTTP Cookie File", "# Generated by Генератор рилсов", ""]
    for c in cookies:
        domain = c.get("domain") or ""
        if not domain:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        cpath = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = str(int(c.get("expires") or c.get("expiry") or 0))
        name = c.get("name") or ""
        value = c.get("value") or ""
        if not name:
            continue
        lines.append(
            "\t".join([domain, include_sub, cpath, secure, expires, name, value])
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _cookies_from_browser_cookie3(browser: str) -> list[dict]:
    import browser_cookie3

    loaders = {
        "chrome": browser_cookie3.chrome,
        "edge": browser_cookie3.edge,
        "brave": getattr(browser_cookie3, "brave", None),
        "firefox": browser_cookie3.firefox,
        "opera": getattr(browser_cookie3, "opera", None),
        "vivaldi": getattr(browser_cookie3, "vivaldi", None),
    }
    loader = loaders.get(browser)
    if loader is None:
        raise RuntimeError(f"Браузер не поддерживается: {browser}")

    # Сначала пробуем только Instagram, потом общий jar
    jar = None
    try:
        jar = loader(domain_name="instagram.com")
    except Exception:
        jar = loader()

    out: list[dict] = []
    for c in jar:
        domain = getattr(c, "domain", "") or ""
        if "instagram" not in domain.lower():
            continue
        out.append(
            {
                "domain": domain if domain.startswith(".") else domain,
                "name": c.name,
                "value": c.value,
                "path": getattr(c, "path", None) or "/",
                "secure": bool(getattr(c, "secure", False)),
                "expires": getattr(c, "expires", None) or 0,
            }
        )
    return out


def _probe_yt_dlp_browser(browser: str) -> bool:
    """Проверяет, что yt-dlp может прочитать cookies браузера."""
    import yt_dlp

    opts = {
        "quiet": True,
        "no_warnings": True,
        "ignoreerrors": True,
        "skip_download": True,
        "cookiesfrombrowser": (browser,),
    }
    try:
        with yt_dlp.YoutubeDL(opts) as ydl:
            # Любой лёгкий URL — важно, что cookies загрузились без CookieLoadError
            ydl.cookiejar.clear()
            # force load by creating YoutubeDL — cookie load happens on extract
            ydl.extract_info("https://www.instagram.com/", download=False)
        return True
    except Exception as exc:  # noqa: BLE001
        msg = str(exc).lower()
        if "cookie" in msg or "dpapi" in msg or "decrypt" in msg:
            return False
        # Другие ошибки Instagram (429 и т.п.) — cookies при этом могли загрузиться
        return "cookie" not in msg


def _export_cookies_via_ytdlp(browser: str, out_path: Path) -> int:
    """Читает cookies браузера через yt-dlp и сохраняет Netscape-файл. Возвращает число cookies."""
    import yt_dlp
    from http.cookiejar import MozillaCookieJar

    opts = {
        "quiet": True,
        "no_warnings": True,
        "ignoreerrors": True,
        "skip_download": True,
        "cookiesfrombrowser": (browser,),
    }
    with yt_dlp.YoutubeDL(opts) as ydl:
        try:
            ydl.extract_info("https://www.instagram.com/accounts/login/", download=False)
        except Exception:
            pass
        src = ydl.cookiejar
        count = len(list(src))
        if count <= 0:
            return 0
        out_path.parent.mkdir(parents=True, exist_ok=True)
        mj = MozillaCookieJar(str(out_path))
        for c in src:
            try:
                mj.set_cookie(c)
            except Exception:
                continue
        mj.save(ignore_discard=True, ignore_expires=True)
        return count


def pull_cookies_from_browser(
    browser: str | None = None,
    *,
    on_log: ProgressCb | None = None,
) -> tuple[Path, str]:
    """
    Тянет cookies Instagram из браузера в assets/cookies_instagram.txt.
    Возвращает (path, browser_name).
    """
    ASSETS.mkdir(parents=True, exist_ok=True)
    cfg = load_ig_config()
    preferred = browser or cfg.get("browser") or "auto"

    browsers: list[str]
    if preferred in {"auto", "нет", "none", ""}:
        remembered = cfg.get("last_ok_browser")
        browsers = []
        if remembered:
            browsers.append(remembered)
        browsers.extend([b for b in BROWSER_ORDER if b not in browsers])
    else:
        browsers = [preferred]

    errors: list[str] = []
    for b in browsers:
        _log(on_log, f"Читаю cookies из {b}…")

        # 1) Надёжный путь: yt-dlp читает Chromium/Opera и пишет Netscape
        try:
            n = _export_cookies_via_ytdlp(b, COOKIES_FILE)
            if n > 0 and cookies_file_ok(COOKIES_FILE):
                cfg["last_ok_browser"] = b
                cfg["use_ytdlp_browser"] = b
                cfg["browser"] = preferred if preferred != "auto" else "auto"
                save_ig_config(cfg)
                _log(on_log, f"OK: сохранено {n} cookies -> {COOKIES_FILE.name} ({b})")
                return COOKIES_FILE, b
            errors.append(f"{b}/yt-dlp-export: cookies пустые или без Instagram")
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{b}/yt-dlp-export: {exc}")

        # 2) browser_cookie3
        try:
            cookies = _cookies_from_browser_cookie3(b)
            if cookies:
                path = _write_netscape(cookies, COOKIES_FILE)
                cfg["last_ok_browser"] = b
                cfg["browser"] = preferred if preferred != "auto" else "auto"
                save_ig_config(cfg)
                _log(on_log, f"OK: сохранено {len(cookies)} cookies -> {path.name} ({b})")
                return path, b
            errors.append(f"{b}: cookies Instagram пустые")
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{b}/browser_cookie3: {exc}")

        # 3) хотя бы cookiesfrombrowser без файла
        try:
            if _probe_yt_dlp_browser(b):
                cfg["last_ok_browser"] = b
                cfg["use_ytdlp_browser"] = b
                save_ig_config(cfg)
                _log(on_log, f"OK: yt-dlp видит cookies браузера {b} (без файла)")
                return Path(""), b
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{b}/yt-dlp: {exc}")

    raise RuntimeError(
        "Не удалось взять cookies из браузера.\n\n"
        "Что сделать:\n"
        "1) Полностью закройте Opera/Chrome и нажмите «Подтянуть cookies» снова\n"
        "2) Или расширение Get cookies.txt LOCALLY - сохраните файл и укажите его\n"
        "3) Убедитесь, что в браузере открыт instagram.com и вы вошли в аккаунт\n\n"
        + "\n".join(errors[:6])
    )


def resolve_cookie_settings(
    *,
    cookies_from_browser: str | None,
    cookies_file: Path | None,
    on_log: ProgressCb | None = None,
    auto_pull: bool = True,
) -> tuple[str | None, Path | None]:
    """
    Итог для yt-dlp: (browser_name | None, cookies_file | None).
    Если выбран auto — подтягивает cookies из браузера ПК.
    """
    # Явный файл пользователя — приоритет, если в нём есть sessionid
    if cookies_file and cookies_file.exists():
        if cookies_file_ok(cookies_file):
            _log(on_log, f"Cookies файл: {cookies_file.name}")
            return None, cookies_file
        _log(
            on_log,
            f"В файле {cookies_file.name} нет sessionid — обновляю cookies из браузера",
        )

    # Уже сохранённый автофайл с живым sessionid
    if cookies_file_ok(COOKIES_FILE):
        _log(on_log, f"Использую сохранённые cookies: {COOKIES_FILE.name}")
        return None, COOKIES_FILE
    if COOKIES_FILE.exists():
        _log(
            on_log,
            "Сохранённые cookies без sessionid — тяну свежие из браузера (войдите в Instagram)",
        )

    choice = (cookies_from_browser or "auto").strip().lower()
    if choice in {"нет", "none", "no"}:
        return None, None

    cfg = load_ig_config()

    if not auto_pull:
        if choice == "auto":
            b = cfg.get("last_ok_browser") or cfg.get("use_ytdlp_browser")
            return (b if b else "chrome"), None
        return choice, None

    # Автоподтягивание
    try:
        path, browser = pull_cookies_from_browser(
            None if choice == "auto" else choice,
            on_log=on_log,
        )
        if path and path.exists() and cookies_file_ok(path):
            return None, path
        # Файл не получился, но браузер читается yt-dlp
        return browser, None
    except Exception as exc:  # noqa: BLE001
        _log(on_log, f"Автоcookies: {exc}")
        # Последний шанс — вернуть любой существующий файл (даже без sessionid):
        # для публичных рилсов yt-dlp иногда срабатывает и так, лучше, чем ничего.
        if cookies_file and cookies_file.exists():
            _log(on_log, f"Резерв: указанный файл {cookies_file.name} (sessionid не найден)")
            return None, cookies_file
        if COOKIES_FILE.exists():
            _log(on_log, f"Резерв: сохранённый {COOKIES_FILE.name} (sessionid не найден)")
            return None, COOKIES_FILE
        # Или просто передать имя браузера в yt-dlp
        if choice == "auto":
            b = cfg.get("last_ok_browser") or "chrome"
            _log(on_log, f"Пробую yt-dlp --cookies-from-browser {b}")
            return b, None
        return choice, None
